-- A course is a language at a level, e.g. Spanish B2, Catalan A1.
create table course (
    id          bigint generated by default as identity primary key,
    language    varchar(100) not null,
    level       varchar(20)  not null,
    description text,
    position    integer      not null default 0,
    created_at  timestamptz  not null default now(),
    unique (language, level)
);

create table category (
    id          bigint generated by default as identity primary key,
    course_id   bigint       not null references course (id) on delete cascade,
    name        varchar(200) not null,
    description text,
    position    integer      not null default 0,
    unique (course_id, name)
);

-- position = the order in which subjects are learned within a course
create table subject (
    id          bigint generated by default as identity primary key,
    category_id bigint       not null references category (id) on delete cascade,
    title       varchar(200) not null,
    description text,
    position    integer      not null default 0
);
create index idx_subject_category on subject (category_id);

-- one lesson per subject (enforced by the unique constraint)
create table lesson (
    id         bigint generated by default as identity primary key,
    subject_id bigint      not null unique references subject (id) on delete cascade,
    content    text        not null default '',
    updated_at timestamptz not null default now()
);

create table vocabulary (
    id          bigint generated by default as identity primary key,
    subject_id  bigint       not null references subject (id) on delete cascade,
    term        varchar(500) not null,
    translation varchar(500) not null,
    notes       text,
    position    integer      not null default 0
);
create index idx_vocabulary_subject on vocabulary (subject_id);
