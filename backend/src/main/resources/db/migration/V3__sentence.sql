-- Example sentences for cloze (fill-the-gap) practice. The Spanish text marks each gap with {{answer}};
-- alternatives inside a gap are separated by "/", e.g. "Si {{tuviera/tuviese}} tiempo, iría."
create table sentence (
    id          bigint generated by default as identity primary key,
    subject_id  bigint        not null references subject (id) on delete cascade,
    text        varchar(1000) not null,
    translation varchar(1000),
    hint        varchar(200),
    explanation text,
    position    integer       not null default 0
);
create index idx_sentence_subject on sentence (subject_id);

