-- Spaced repetition (Leitner boxes). One row per vocabulary item or sentence that has been reviewed at least
-- once; items without a row are "new". Two nullable foreign keys (exactly one set) keep ON DELETE CASCADE working.
create table review_state (
    id                bigint generated by default as identity primary key,
    vocabulary_id     bigint unique references vocabulary (id) on delete cascade,
    sentence_id       bigint unique references sentence (id) on delete cascade,
    box               integer     not null default 0,
    due_at            timestamptz not null default now(),
    first_reviewed_at timestamptz not null default now(),
    last_reviewed_at  timestamptz,
    last_response_ms  integer,
    reviews           integer     not null default 0,
    lapses            integer     not null default 0,
    check ((vocabulary_id is null) <> (sentence_id is null))
);
create index idx_review_state_due on review_state (due_at);

-- Every answer that was reported, for statistics later.
create table review_log (
    id            bigint generated by default as identity primary key,
    vocabulary_id bigint references vocabulary (id) on delete cascade,
    sentence_id   bigint references sentence (id) on delete cascade,
    mode          varchar(20) not null,
    correct       boolean     not null,
    response_ms   integer     not null,
    outcome       varchar(20) not null,
    box_after     integer     not null,
    reviewed_at   timestamptz not null default now(),
    check ((vocabulary_id is null) <> (sentence_id is null))
);
